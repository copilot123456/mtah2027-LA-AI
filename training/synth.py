"""Synthetic "external games" for smoke tests — a moving ball on a drawn pitch.

Real training needs a real external dataset. Before one is on the machine, and every
time the environment changes, the whole chain (manifest -> tiles -> RT-DETR training
-> full-frame evaluation -> FoT training) should be proven to run on the GPU in a few
minutes. This module writes a tiny dataset for that purpose, in exactly the format
:mod:`training.manifest` expects, so the same commands work on it as on real data.

Each game is a short clip of a green pitch with lines, one small bright ball on a
smooth path, a few static ball-like distractors (the "penalty spots" a detector must
learn to ignore) and some frames where the ball is hidden. Everything is generated
from a seed; nothing is downloaded and nothing comes from the provided match.

A model trained on this proves the plumbing, not ball detection: never report its
metrics as results, and never use it for inference on a real match.

    python -m training.synth --out data/external/synth --games 3 --frames 120
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from training.compliance import assert_external

DATASET_NAME = "synthetic-smoke"
LICENSE = "generated by training/synth.py - no third-party content"
SOURCE_URL = "training/synth.py (procedurally generated)"


def ball_path(n_frames: int, width: int, height: int, rng: np.random.Generator):
    """Smooth pixel path ``(x, y)`` of length ``n_frames`` kept inside the frame."""
    margin = 30.0
    t = np.arange(n_frames, dtype=np.float64)
    phase = rng.uniform(0, 2 * np.pi, size=4)
    period = rng.uniform(60.0, 140.0, size=4)
    x = width / 2 + (width / 2 - margin) * 0.85 * np.sin(2 * np.pi * t / period[0] + phase[0])
    x += 0.08 * width * np.sin(2 * np.pi * t / period[1] + phase[1])
    y = height / 2 + (height / 2 - margin) * 0.80 * np.sin(2 * np.pi * t / period[2] + phase[2])
    y += 0.06 * height * np.sin(2 * np.pi * t / period[3] + phase[3])
    return np.clip(x, margin, width - margin), np.clip(y, margin, height - margin)


def hidden_mask(n_frames: int, rng: np.random.Generator, n_gaps: int = 3,
                max_len: int = 6) -> np.ndarray:
    """Boolean mask of frames where the ball is not drawn (short occlusions)."""
    hidden = np.zeros(n_frames, dtype=bool)
    if n_frames < 4 * max_len:
        return hidden
    for _ in range(n_gaps):
        length = int(rng.integers(1, max_len + 1))
        start = int(rng.integers(max_len, n_frames - 2 * max_len))
        hidden[start:start + length] = True
    return hidden


def render_frame(width: int, height: int, ball, distractors, rng: np.random.Generator,
                 radius: int = 5):
    """One BGR frame: pitch, lines, static distractors, sensor noise, optional ball."""
    import cv2

    image = np.empty((height, width, 3), dtype=np.uint8)
    image[:] = (40, 130, 40)
    line = (235, 235, 235)
    pad_x, pad_y = int(0.08 * width), int(0.08 * height)
    cv2.rectangle(image, (pad_x, pad_y), (width - pad_x, height - pad_y), line, 2)
    cv2.line(image, (width // 2, pad_y), (width // 2, height - pad_y), line, 2)
    cv2.circle(image, (width // 2, height // 2), int(0.12 * height), line, 2)
    for dx, dy in distractors:
        cv2.circle(image, (int(dx), int(dy)), 3, (225, 225, 225), -1, lineType=cv2.LINE_AA)
    noise = rng.integers(-6, 7, size=image.shape, dtype=np.int16)
    image = np.clip(image.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    if ball is not None:
        cv2.circle(image, (int(round(ball[0])), int(round(ball[1]))), radius,
                   (250, 250, 250), -1, lineType=cv2.LINE_AA)
    return image


def write_game(out_dir: Path, game_id: str, n_frames: int, width: int, height: int,
               seed: int, as_video: bool = False, radius: int = 5) -> dict:
    """Render one synthetic game and its annotations; return its manifest entry."""
    import cv2

    rng = np.random.default_rng(seed)
    game_dir = out_dir / f"game{game_id}"
    game_dir.mkdir(parents=True, exist_ok=True)
    xs, ys = ball_path(n_frames, width, height, rng)
    hidden = hidden_mask(n_frames, rng)
    distractors = np.column_stack([rng.uniform(40, width - 40, size=4),
                                   rng.uniform(40, height - 40, size=4)])

    writer = None
    frames_dir = game_dir / "img1"
    if as_video:
        writer = cv2.VideoWriter(str(game_dir / "video.mp4"),
                                 cv2.VideoWriter_fourcc(*"mp4v"), 25.0, (width, height))
        if not writer.isOpened():
            raise IOError("cv2.VideoWriter could not open an mp4v stream; use frames")
    else:
        frames_dir.mkdir(exist_ok=True)

    rows = []
    for index in range(n_frames):
        ball = None if hidden[index] else (xs[index], ys[index])
        image = render_frame(width, height, ball, distractors, rng, radius)
        if writer is not None:
            writer.write(image)
        else:
            cv2.imwrite(str(frames_dir / f"{index:06d}.png"), image)
        if ball is not None:
            rows.append((index, float(xs[index]), float(ys[index]),
                         2.0 * radius + 2, 2.0 * radius + 2))
    if writer is not None:
        writer.release()

    pd.DataFrame(rows, columns=["frame", "x", "y", "w", "h"]).to_csv(
        game_dir / "ball.csv", index=False)
    entry = {"id": game_id, "annotations": f"game{game_id}/ball.csv", "fps": 25,
             "frame_offset": 0}
    entry["video" if as_video else "frames_dir"] = (
        f"game{game_id}/video.mp4" if as_video else f"game{game_id}/img1")
    return entry


def write_dataset(out_dir, n_games: int = 3, n_frames: int = 120, width: int = 640,
                  height: int = 480, seed: int = 0, as_video: bool = False) -> Path:
    """Write ``n_games`` synthetic games plus ``manifest.json``; return its path."""
    out_dir = Path(out_dir).expanduser()
    assert_external(out_dir, what="synthetic dataset output")
    out_dir.mkdir(parents=True, exist_ok=True)
    games = [write_game(out_dir, str(index + 1), n_frames, width, height,
                        seed * 1000 + index, as_video) for index in range(n_games)]
    manifest = {"dataset": DATASET_NAME, "license": LICENSE, "source_url": SOURCE_URL,
                "notes": "Smoke-test data only. Proves the pipeline runs; says nothing"
                         " about real ball detection.",
                "games": games}
    target = out_dir / "manifest.json"
    target.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    """Generate a synthetic smoke-test dataset."""
    import argparse

    parser = argparse.ArgumentParser(
        prog="python -m training.synth",
        description="Write a tiny synthetic external dataset for smoke tests.")
    parser.add_argument("--out", required=True)
    parser.add_argument("--games", type=int, default=3)
    parser.add_argument("--frames", type=int, default=120)
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=480)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--video", action="store_true",
                        help="write mp4 clips instead of PNG frame folders")
    args = parser.parse_args(argv)

    manifest = write_dataset(args.out, args.games, args.frames, args.width, args.height,
                             args.seed, args.video)
    print(f"synthetic dataset written: {manifest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
